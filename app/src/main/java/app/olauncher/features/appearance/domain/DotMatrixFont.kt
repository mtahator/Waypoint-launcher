package app.olauncher.features.appearance.domain

/**
 * 5×7 dot-matrix glyphs (Nothing-style clock and captions). Each glyph is 7 rows; '#' = lit dot.
 * Unknown characters return null so callers can fall back to normal text.
 */
object DotMatrixFont {
    const val ROWS = 7

    private val GLYPHS: Map<Char, Array<String>> = mapOf(
        '0' to g(".###.", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."),
        '1' to g("..#..", ".##..", "..#..", "..#..", "..#..", "..#..", ".###."),
        '2' to g(".###.", "#...#", "....#", "...#.", "..#..", ".#...", "#####"),
        '3' to g("#####", "...#.", "..#..", "...#.", "....#", "#...#", ".###."),
        '4' to g("...#.", "..##.", ".#.#.", "#..#.", "#####", "...#.", "...#."),
        '5' to g("#####", "#....", "####.", "....#", "....#", "#...#", ".###."),
        '6' to g("..##.", ".#...", "#....", "####.", "#...#", "#...#", ".###."),
        '7' to g("#####", "....#", "...#.", "..#..", ".#...", ".#...", ".#..."),
        '8' to g(".###.", "#...#", "#...#", ".###.", "#...#", "#...#", ".###."),
        '9' to g(".###.", "#...#", "#...#", ".####", "....#", "...#.", ".##.."),
        'A' to g(".###.", "#...#", "#...#", "#...#", "#####", "#...#", "#...#"),
        'B' to g("####.", "#...#", "#...#", "####.", "#...#", "#...#", "####."),
        'C' to g(".###.", "#...#", "#....", "#....", "#....", "#...#", ".###."),
        'D' to g("###..", "#..#.", "#...#", "#...#", "#...#", "#..#.", "###.."),
        'E' to g("#####", "#....", "#....", "####.", "#....", "#....", "#####"),
        'F' to g("#####", "#....", "#....", "####.", "#....", "#....", "#...."),
        'G' to g(".###.", "#...#", "#....", "#.###", "#...#", "#...#", ".####"),
        'H' to g("#...#", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"),
        'I' to g(".###.", "..#..", "..#..", "..#..", "..#..", "..#..", ".###."),
        'J' to g("..###", "...#.", "...#.", "...#.", "...#.", "#..#.", ".##.."),
        'K' to g("#...#", "#..#.", "#.#..", "##...", "#.#..", "#..#.", "#...#"),
        'L' to g("#....", "#....", "#....", "#....", "#....", "#....", "#####"),
        'M' to g("#...#", "##.##", "#.#.#", "#.#.#", "#...#", "#...#", "#...#"),
        'N' to g("#...#", "#...#", "##..#", "#.#.#", "#..##", "#...#", "#...#"),
        'O' to g(".###.", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."),
        'P' to g("####.", "#...#", "#...#", "####.", "#....", "#....", "#...."),
        'Q' to g(".###.", "#...#", "#...#", "#...#", "#.#.#", "#..#.", ".##.#"),
        'R' to g("####.", "#...#", "#...#", "####.", "#.#..", "#..#.", "#...#"),
        'S' to g(".####", "#....", "#....", ".###.", "....#", "....#", "####."),
        'T' to g("#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#.."),
        'U' to g("#...#", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."),
        'V' to g("#...#", "#...#", "#...#", "#...#", "#...#", ".#.#.", "..#.."),
        'W' to g("#...#", "#...#", "#...#", "#.#.#", "#.#.#", "#.#.#", ".#.#."),
        'X' to g("#...#", "#...#", ".#.#.", "..#..", ".#.#.", "#...#", "#...#"),
        'Y' to g("#...#", "#...#", "#...#", ".#.#.", "..#..", "..#..", "..#.."),
        'Z' to g("#####", "....#", "...#.", "..#..", ".#...", "#....", "#####"),
        ':' to g(".", ".", "#", ".", "#", ".", "."),
        '.' to g(".", ".", ".", ".", ".", ".", "#"),
        ',' to g("..", "..", "..", "..", "..", ".#", "#."),
        '-' to g("...", "...", "...", "###", "...", "...", "..."),
        '+' to g(".....", "..#..", "..#..", "#####", "..#..", "..#..", "....."),
        '/' to g("....#", "...#.", "...#.", "..#..", ".#...", ".#...", "#...."),
        '%' to g("##..#", "##..#", "...#.", "..#..", ".#...", "#..##", "#..##"),
        '°' to g(".#.", "#.#", ".#.", "...", "...", "...", "..."),
        ' ' to g("..", "..", "..", "..", "..", "..", ".."),
    )

    private fun g(vararg rows: String): Array<String> = arrayOf(*rows)

    /** Latin caps; Persian/Arabic-Indic digits map to ASCII so the clock renders in any locale. */
    fun normalize(c: Char): Char = when (c) {
        in '۰'..'۹' -> '0' + (c - '۰')
        in '٠'..'٩' -> '0' + (c - '٠')
        ' ', ' ' -> ' '
        else -> c.uppercaseChar()
    }

    fun glyph(c: Char): Array<String>? = GLYPHS[normalize(c)]

    fun supports(text: CharSequence): Boolean = text.all { glyph(it) != null }

    /** Width in dot columns, with one empty column between glyphs. */
    fun width(text: CharSequence): Int =
        text.sumOf { (glyph(it)?.get(0)?.length ?: 0) } + (text.length - 1).coerceAtLeast(0)
}
