package app.olauncher.features.export.domain

import app.olauncher.features.transactions.domain.Money
import app.olauncher.features.transactions.domain.Transaction
import java.time.Instant
import java.time.ZoneOffset
import java.time.format.DateTimeFormatter

/** Locale-independent RFC 4180 CSV for the ledger. See docs/csv-format.md. */
object CsvFormatter {
    const val LINE_END = "\r\n"
    const val BOM = "﻿"
    private val ISO: DateTimeFormatter = DateTimeFormatter.ISO_OFFSET_DATE_TIME

    fun header(columns: List<CsvColumn>): String = columns.joinToString(",") { it.header } + LINE_END

    fun row(t: Transaction, columns: List<CsvColumn>): String = columns.joinToString(",") { col ->
        when (col) {
            CsvColumn.TRANSACTION_DATE -> t.transactionAt?.let(::isoUtc) ?: isoUtc(t.receivedAt)
            CsvColumn.RECEIVED_AT -> isoUtc(t.receivedAt)
            CsvColumn.SOURCE -> CsvSanitizer.textField(t.sourceLabel)
            CsvColumn.MERCHANT -> CsvSanitizer.textField(t.merchant)
            // Generated by the app from integers: never a formula, exempt from neutralization.
            CsvColumn.AMOUNT -> t.amountMinor?.let { Money.formatPlain(it, t.currency) } ?: ""
            CsvColumn.CURRENCY -> CsvSanitizer.textField(t.currency)
            CsvColumn.DIRECTION -> t.direction?.key ?: ""
            CsvColumn.STATUS -> t.status.key
            CsvColumn.NOTE -> CsvSanitizer.textField(t.userNote)
        }
    } + LINE_END

    fun format(rows: List<Transaction>, columns: List<CsvColumn>, bom: Boolean = false): String = buildString {
        if (bom) append(BOM)
        append(header(columns))
        rows.forEach { append(row(it, columns)) }
    }

    /** `2026-10-03T12:15:00Z` */
    fun isoUtc(epochMillis: Long): String =
        ISO.format(Instant.ofEpochMilli(epochMillis).atOffset(ZoneOffset.UTC).withNano(0))

    /** `ledger-export-20261027.csv` — never contains personal data. */
    fun suggestedFileName(nowMillis: Long): String =
        "ledger-export-" + DateTimeFormatter.BASIC_ISO_DATE.format(Instant.ofEpochMilli(nowMillis).atOffset(ZoneOffset.UTC).toLocalDate()) + ".csv"
}
